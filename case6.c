/*
 Единицы длины пронумерованы следующим образом: 1 — дециметр,
 2 — километр, 3 — метр, 4 — миллиметр, 5 — сантиметр. Дан номер
 единицы длины (целое число в диапазоне 1–5) и длина отрезка в этих
 единицах (вещественное число). Найти длину отрезка в метрах
 Выполнил: Мартиросян Сергей, группа: 201ИС-25.
 */
#include <stdio.h>
int main (void) {
    int a; // единица длины
    float b; // длина отрезка
    scanf ("%d", &a);
    scanf ("%f", &b);
    switch (a) {
        case 1:
            printf ("%f", b / 10);
            break;
        case 2:
            printf ("%f", b * 1000);
            break;
        case 3:
            printf ("%f", b );
            break;
        case 4:
            printf ("%f", b / 1000);
            break;
        case 5:
            printf ("%f", b / 100);
            break;
        default:
            printf ("Error\n");
    }
    
    

    return 0;
}
    
